-- =========================================================================
-- v83: sys_error 增加"上报当时的用户昵称"快照
--
-- 动机：这张表是排查现场用的。直接查库时只有一串 user_id 看不出是谁；
-- 而管理后台现在显示的昵称是 LEFT JOIN "user" 实时取的，用户改了昵称之后，
-- 历史记录显示的昵称会跟着变，跟当时反馈的现场对不上。
-- 因此在写入时留一份"上报当时"的昵称快照。
--
-- 展示口径：COALESCE(快照, user 表的实时昵称)。
-- 改造前的老记录本列为空，继续走实时昵称，管理端不会倒退。
--
-- 刻意不回填老数据：把"当前昵称"写进历史记录会伪造出一份当时并不存在的快照，
-- 比留空更糟；留空由 COALESCE 回退即可。
--
-- 列位置说明：PostgreSQL 的 ADD COLUMN 只能追加到末尾，无法指定
-- "排在 user_id 之后"（那是 MySQL 专有语法）。列顺序统一在
-- 实体字段、VO 构造参数、SELECT 列表与管理端展示里紧跟 user_id。
-- =========================================================================

ALTER TABLE "sys_error" ADD COLUMN IF NOT EXISTS "nick_name" VARCHAR(100);

COMMENT ON COLUMN "sys_error"."nick_name" IS '上报当时该用户的昵称快照；未登录/游客与服务端自身产生的记录为空，展示时回退到 user 表的实时昵称';
